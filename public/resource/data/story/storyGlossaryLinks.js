/**
 * Ищет ссылки для конкретной реплики. storySceneIndex/screenIndex —
 * 0-based индексы, как их использует StoryScene (this.storySceneIndex,
 * this.screenIndex) — переводим их в 1-based scene/screen из списка выше.
 * Возвращает массив найденных ссылок или null, если для этой реплики
 * ссылок нет.
 */
window.VN.data.getGlossaryLinksFor = function (storySceneIndex, screenIndex) {
  const scene = storySceneIndex + 1;
  const screen = screenIndex + 1;
  const found = window.VN.data.storyGlossaryLinks.filter(
    (entry) => entry.scene === scene && entry.screen === screen
  );
  return found.length ? found : null;
};
